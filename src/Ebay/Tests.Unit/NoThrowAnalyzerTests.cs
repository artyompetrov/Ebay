using System.Collections.Immutable;
using Analyzers;
using AwesomeAssertions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Tests.Unit;

[TestFixture]
[TestOf(typeof(NoThrowAnalyzer))]
public sealed class NoThrowAnalyzerTests
{
    [Test]
    public async Task ReportsThrowStatement()
    {
        const string source = """
                              public static class C
                              {
                                  public static void M() { throw new System.InvalidOperationException(); }
                              }
                              """;

        var diagnostics = await AnalyzeAsync(source, "C.cs");

        diagnostics.Should().ContainSingle().Which.Id.Should().Be(NoThrowAnalyzer.DiagnosticId);
    }

    [Test]
    public async Task ReportsThrowExpression()
    {
        const string source = """
                              public static class C
                              {
                                  public static string M(string? value) => value ?? throw new System.ArgumentNullException(nameof(value));
                              }
                              """;

        var diagnostics = await AnalyzeAsync(source, "C.cs");

        diagnostics.Should().ContainSingle().Which.Id.Should().Be(NoThrowAnalyzer.DiagnosticId);
    }

    [Test]
    public async Task ReportsRethrowOfAnotherExceptionObject()
    {
        const string source = """
                              public static class C
                              {
                                  public static void M(System.Action action)
                                  {
                                      try { action(); }
                                      catch (System.Exception e) { throw e; }
                                  }
                              }
                              """;

        var diagnostics = await AnalyzeAsync(source, "C.cs");

        diagnostics.Should().ContainSingle().Which.Id.Should().Be(NoThrowAnalyzer.DiagnosticId);
    }

    [Test]
    public async Task AllowsBareRethrowInCatchBlock()
    {
        const string source = """
                              public static class C
                              {
                                  public static void M(System.Action action)
                                  {
                                      try { action(); }
                                      catch (System.Exception) { throw; }
                                  }
                              }
                              """;

        var diagnostics = await AnalyzeAsync(source, "C.cs");

        diagnostics.Should().BeEmpty();
    }

    [Test]
    public async Task SkipsToolGeneratedCode()
    {
        const string source = """
                              // <auto-generated />
                              public static class C
                              {
                                  public static void M() { throw new System.InvalidOperationException(); }
                              }
                              """;

        var diagnostics = await AnalyzeAsync(source, "Generated/Client.cs");

        diagnostics.Should().BeEmpty();
    }

    [Test]
    public async Task ReportsCodeWrittenInRazorMarkup()
    {
        const string source = """
                              // <auto-generated/>
                              public class Page
                              {
                              #line 10 "Pages/Page.razor"
                                  public void M() { throw new System.InvalidOperationException(); }
                              #line default
                              #line hidden
                              }
                              """;

        var diagnostics = await AnalyzeAsync(source, "Pages_Page_razor.g.cs");

        diagnostics.Should().ContainSingle().Which.Location.GetMappedLineSpan().Path.Should().Be("Pages/Page.razor");
    }

    [Test]
    public async Task SkipsRazorGeneratorPlumbing()
    {
        const string source = """
                              // <auto-generated/>
                              public class Page
                              {
                              #line hidden
                                  public object Service { get => field ?? throw new System.InvalidOperationException(); set => field = value; }
                              #line default
                              }
                              """;

        var diagnostics = await AnalyzeAsync(source, "Pages_Page_razor.g.cs");

        diagnostics.Should().BeEmpty();
    }

    private static async Task<ImmutableArray<Diagnostic>> AnalyzeAsync(string source, string path)
    {
        var syntaxTree = CSharpSyntaxTree.ParseText(
            source,
            new CSharpParseOptions(LanguageVersion.Preview),
            path: path);
        var compilation = CSharpCompilation.Create(
            assemblyName: "AnalyzedAssembly",
            syntaxTrees: [syntaxTree],
            references: [MetadataReference.CreateFromFile(typeof(object).Assembly.Location)],
            options: new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, nullableContextOptions: NullableContextOptions.Enable));

        return await compilation
            .WithAnalyzers([new NoThrowAnalyzer()])
            .GetAnalyzerDiagnosticsAsync(CancellationToken.None);
    }
}
