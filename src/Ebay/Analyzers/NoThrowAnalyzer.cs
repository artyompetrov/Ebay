using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Analyzers;

/// <summary>
/// Forbids raising exceptions in our code: expected failures are returned as <c>OneOf</c> results instead.
/// Reports every <c>throw</c> statement and <c>throw</c> expression that raises an exception object.
/// A bare <c>throw;</c> inside a <c>catch</c> block is allowed: it lets an exception raised by a library
/// propagate unchanged after the block recorded it (for example marked a span as failed), it raises nothing new.
/// Code generated by tools (NSwag clients and controllers, EF migrations) is skipped; code generated from our
/// own Razor markup (<c>.razor</c>/<c>.cshtml</c>) is checked, because its <c>@code</c> blocks are hand-written.
/// </summary>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class NoThrowAnalyzer : DiagnosticAnalyzer
{
    /// <summary>
    /// The diagnostic id.
    /// </summary>
    public const string DiagnosticId = "EBAY0001";

    private static readonly DiagnosticDescriptor Rule = new(
        id: DiagnosticId,
        title: "Do not throw exceptions",
        messageFormat: "Do not throw exceptions; return the failure as a OneOf result instead",
        category: "Design",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true,
        description: "Failures are part of a method's signature: return OneOf<TResult, TError> (OneOf.Types.Success/NotFound, " +
                     "Server.Domain.Errors.DomainError) instead of throwing. Only a bare 'throw;' that rethrows the caught exception is allowed.");

    /// <inheritdoc />
    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics { get; } = [Rule];

    /// <inheritdoc />
    public override void Initialize(AnalysisContext context)
    {
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics);
        context.EnableConcurrentExecution();
        context.RegisterSyntaxNodeAction(AnalyzeThrow, SyntaxKind.ThrowStatement, SyntaxKind.ThrowExpression);
    }

    private static void AnalyzeThrow(SyntaxNodeAnalysisContext context)
    {
        if (context.IsGeneratedCode && !IsWrittenInRazorMarkup(context.Node))
        {
            return;
        }

        if (context.Node is ThrowStatementSyntax { Expression: null })
        {
            return;
        }

        context.ReportDiagnostic(Diagnostic.Create(Rule, context.Node.GetLocation()));
    }

    // The Razor source generator names its output after the markup file: Pages/Product.razor -> Pages_Product_razor.g.cs.
    private static readonly string[] RazorGeneratedFileSuffixes = ["_razor.g.cs", "_cshtml.g.cs", ".razor.g.cs", ".cshtml.g.cs"];

    // Code from the markup is mapped back to it with #line directives; the generator's own plumbing is not.
    private static bool IsWrittenInRazorMarkup(SyntaxNode node) =>
        RazorGeneratedFileSuffixes.Any(suffix => node.SyntaxTree.FilePath.EndsWith(suffix, StringComparison.OrdinalIgnoreCase)) &&
        node.SyntaxTree.GetLineVisibility(node.SpanStart) == LineVisibility.Visible &&
        node.GetLocation().GetMappedLineSpan().HasMappedPath;
}
