using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;

namespace Analyzers;

/// <summary>
/// Forbids raising exceptions in our code, with two kinds of failures in mind:
/// <list type="bullet">
/// <item>an expected failure (bad input, a business rule, a missing entity, a failing downstream system) is returned
/// as a <c>OneOf</c> result;</item>
/// <item>a bug - a state the code's own invariants rule out - is a "panic", raised only with
/// <c>throw new UnreachableException(...)</c>.</item>
/// </list>
/// Reports every other <c>throw</c> statement and <c>throw</c> expression. A bare <c>throw;</c> inside a <c>catch</c>
/// block is allowed: it lets an exception raised by a library propagate unchanged after the block recorded it.
/// Code generated by tools (NSwag clients and controllers, EF migrations) is skipped; code generated from our
/// own Razor markup (<c>.razor</c>/<c>.cshtml</c>) is checked, because its <c>@code</c> blocks are hand-written.
/// </summary>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class NoThrowAnalyzer : DiagnosticAnalyzer
{
    /// <summary>
    /// The diagnostic id.
    /// </summary>
    public const string DiagnosticId = "EBAY0001";

    private const string PanicExceptionTypeName = "System.Diagnostics.UnreachableException";

    private static readonly DiagnosticDescriptor Rule = new(
        id: DiagnosticId,
        title: "Do not throw exceptions",
        messageFormat: "Do not throw '{0}'. An expected failure (bad input, business rule, missing entity, failing downstream system) " +
                       "must be returned as a OneOf result (OneOf.Types.Success/NotFound, Server.Domain.Errors.DomainError, OneOf.Types.Error<string>). " +
                       "A bug (a state the code's invariants rule out) is a panic: use only 'throw new UnreachableException(...)'.",
        category: "Design",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true,
        description: "Expected failures are part of a method's signature and are returned as OneOf results. Bugs are panics raised " +
                     "only with 'throw new UnreachableException(...)'. A bare 'throw;' that rethrows the caught exception is allowed.");

    /// <inheritdoc />
    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics { get; } = [Rule];

    /// <inheritdoc />
    public override void Initialize(AnalysisContext context)
    {
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics);
        context.EnableConcurrentExecution();
        context.RegisterCompilationStartAction(static compilationContext =>
        {
            var panicExceptionType = compilationContext.Compilation.GetTypeByMetadataName(PanicExceptionTypeName);
            compilationContext.RegisterSyntaxNodeAction(
                nodeContext => AnalyzeThrow(nodeContext, panicExceptionType),
                SyntaxKind.ThrowStatement,
                SyntaxKind.ThrowExpression);
        });
    }

    private static void AnalyzeThrow(SyntaxNodeAnalysisContext context, INamedTypeSymbol? panicExceptionType)
    {
        if (context.IsGeneratedCode && !IsWrittenInRazorMarkup(context.Node))
        {
            return;
        }

        var thrown = context.Node switch
        {
            ThrowStatementSyntax statement => statement.Expression,
            ThrowExpressionSyntax expression => expression.Expression,
            _ => null
        };

        // A bare `throw;` rethrows the caught exception.
        if (thrown is null)
        {
            return;
        }

        var thrownType = context.SemanticModel.GetTypeInfo(thrown, context.CancellationToken).Type;
        if (panicExceptionType is not null && SymbolEqualityComparer.Default.Equals(thrownType, panicExceptionType))
        {
            return;
        }

        context.ReportDiagnostic(Diagnostic.Create(
            Rule,
            context.Node.GetLocation(),
            thrownType?.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat) ?? thrown.ToString()));
    }

    // The Razor source generator names its output after the markup file: Pages/Product.razor -> Pages_Product_razor.g.cs.
    private static readonly string[] RazorGeneratedFileSuffixes = ["_razor.g.cs", "_cshtml.g.cs", ".razor.g.cs", ".cshtml.g.cs"];

    // Code from the markup is mapped back to it with #line directives; the generator's own plumbing is not.
    private static bool IsWrittenInRazorMarkup(SyntaxNode node) =>
        RazorGeneratedFileSuffixes.Any(suffix => node.SyntaxTree.FilePath.EndsWith(suffix, StringComparison.OrdinalIgnoreCase)) &&
        node.SyntaxTree.GetLineVisibility(node.SpanStart) == LineVisibility.Visible &&
        node.GetLocation().GetMappedLineSpan().HasMappedPath;
}
